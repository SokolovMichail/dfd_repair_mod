"""Генерирует переходники прокси-DLL winhttp из таблицы экспорта системной winhttp.dll.

    python tools/gen_winhttp_proxy.py [путь к winhttp.dll]

Создаёт loader/winhttp_exports.S (jmp на адрес из g_orig[]), loader/winhttp.def
и loader/winhttp_exports.inc (список имён для GetProcAddress).
"""
import os
import struct
import sys

src = sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.environ.get('SystemRoot', r'C:\Windows'), 'System32', 'winhttp.dll')
d = open(src, 'rb').read()
p = struct.unpack_from('<I', d, 0x3c)[0]
opt = p + 24
assert struct.unpack_from('<H', d, opt)[0] == 0x20b, 'нужна 64-битная winhttp.dll'
nsec = struct.unpack_from('<H', d, p + 6)[0]
sopt = struct.unpack_from('<H', d, p + 20)[0]
secs = [struct.unpack_from('<IIII', d, opt + sopt + 40 * i + 8) for i in range(nsec)]


def r2o(r):
    for vs, va, rs, ra in secs:
        if va <= r < va + max(vs, rs):
            return ra + r - va
    raise ValueError(hex(r))


def cstr(o):
    return d[o:d.index(b'\0', o)].decode()


erva, esz = struct.unpack_from('<II', d, opt + 112)
_, _, _, _, _, base, nfunc, nname, afunc, aname, aord = struct.unpack_from('<IIHHIIIIIII', d, r2o(erva))
names = {}
for i in range(nname):
    idx = struct.unpack_from('<H', d, r2o(aord) + 2 * i)[0]
    names[idx] = cstr(r2o(struct.unpack_from('<I', d, r2o(aname) + 4 * i)[0]))

exports = []  # (ordinal, name)
for i in range(nfunc):
    if not struct.unpack_from('<I', d, r2o(afunc) + 4 * i)[0]:
        continue
    if i not in names:
        sys.exit(f'экспорт только по ординалу #{base + i} не поддержан')
    exports.append((base + i, names[i]))

out = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'loader')
hdr = f'// Generated by tools/gen_winhttp_proxy.py from {os.path.basename(src)} ({len(exports)} exports). Do not edit.\n'

with open(os.path.join(out, 'winhttp_exports.S'), 'w', newline='\n') as f:
    f.write(hdr.replace('//', '#'))
    f.write('    .text\n')
    for k, (_, n) in enumerate(exports):
        f.write(f'    .globl {n}\n    .p2align 4\n{n}:\n    jmp *g_orig+{8 * k}(%rip)\n')

with open(os.path.join(out, 'winhttp.def'), 'w', newline='\n') as f:
    f.write(hdr.replace('//', ';'))
    f.write('LIBRARY winhttp.dll\nEXPORTS\n')
    for o, n in exports:
        f.write(f'    {n} @{o}\n')

with open(os.path.join(out, 'winhttp_exports.inc'), 'w', newline='\n') as f:
    f.write(hdr)
    for _, n in exports:
        f.write(f'"{n}",\n')

print(f'{len(exports)} exports -> {os.path.normpath(out)}')
